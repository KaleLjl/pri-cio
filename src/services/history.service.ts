/**
 * Fetches all history items for a specific user.
 * @param userEmail - The email of the user whose history is to be fetched.
 * @returns A promise that resolves to an array of HistoryItem objects.
 */
export async function getHistoryForUser(
  userEmail: string
): Promise<HistoryItem[]> {
  if (!userEmail) {
    throw new Error("User email is required.");
  }

  try {
    const client = await clientPromise;
    const db = client.db("pri-cio");
    // Use HistoryItem type for now, adjust if DB schema differs
    const historiesCollection = db.collection<HistoryItem>("histories");

    const histories = await historiesCollection
      .find({ userEmail: userEmail })
      .sort({ createdAt: -1 })
      .toArray();

    // Map results to ensure consistent string IDs, etc.
    const formattedHistories = histories.map(
      (history): HistoryItem => ({
        ...history,
        _id: history._id.toString(), // Ensure _id is string
        // Add other necessary transformations if DB schema differs
      })
    );

    return formattedHistories;
  } catch (error) {
    console.error(
      `[HistoryService] Error fetching history for user ${userEmail}:`,
      error
    );
    throw new Error("Failed to fetch history items.");
  }
}

import { uploadToS3 } from "@/lib/s3"; // Import S3 helper
import { CreateHistoryData, CreatedHistoryItem } from "@/lib/types/history"; // Import types
import { OptionalId } from "mongodb"; // Import OptionalId

// Define DB schema if different from HistoryItem (e.g., createdAt is Date)
interface HistoryDBSchema extends Omit<HistoryItem, "_id" | "createdAt"> {
  _id?: ObjectId; // Optional for insertion
  createdAt: Date;
}

/**
 * Creates a new history item, uploading images to S3 first.
 * @param data - Data required to create the history item.
 * @returns A promise resolving to the ID and S3 image URLs of the created item.
 */
export async function createHistoryItem(
  data: CreateHistoryData
): Promise<CreatedHistoryItem> {
  const { userEmail, price, description, images, currency } = data;

  if (!userEmail) {
    throw new Error("User email is required.");
  }
  if (!images || !Array.isArray(images) || images.length === 0) {
    throw new Error("At least one image is required.");
  }

  try {
    // 1. Upload images to S3
    const uploadedImages = await Promise.all(
      images.map(async (image) => {
        if (!image.url) {
          // Assuming image.url contains base64 data URL initially
          throw new Error(
            `Image URL (base64 data) is required for image ID: ${image.id}`
          );
        }
        // Generate a unique filename
        const fileName = `history-${userEmail}-${Date.now()}-${image.id}.jpg`;
        // Upload to S3
        const s3ImageUrl = await uploadToS3(image.url, fileName);
        // Return object with S3 URL
        return {
          id: image.id,
          url: s3ImageUrl, // The S3 URL
          isPrimary: image.isPrimary,
        };
      })
    );

    // 2. Save record to database
    const client = await clientPromise;
    const db = client.db("pri-cio");
    const historiesCollection =
      db.collection<OptionalId<HistoryDBSchema>>("histories");

    const newHistoryDocument: OptionalId<HistoryDBSchema> = {
      // _id will be generated by MongoDB
      userEmail,
      price: price || "", // Default to empty string if undefined
      description: description || "", // Default to empty string if undefined
      images: uploadedImages, // Use images with S3 URLs
      currency,
      createdAt: new Date(),
      // Initialize other optional fields as needed, e.g., exploreId: undefined
    };

    const result = await historiesCollection.insertOne(newHistoryDocument);

    // 3. Return the necessary info (ID and S3 URLs)
    return {
      _id: result.insertedId.toString(),
      images: uploadedImages,
    };
  } catch (error) {
    console.error(
      `[HistoryService] Error creating history item for user ${userEmail}:`,
      error
    );
    // Consider more specific error handling (e.g., S3 upload failure vs. DB failure)
    throw new Error("Failed to create history item.");
  }
}
